package com.nachtraben.soundstage.core.video;

import com.sedmelluq.discord.lavaplayer.tools.JsonBrowser;
import com.sedmelluq.discord.lavaplayer.tools.io.HttpInterface;
import dev.lavalink.youtube.YoutubeAudioSourceManager;
import dev.armadeus.armalib.lavaplayer.shadow.org.apache.http.client.methods.CloseableHttpResponse;
import dev.armadeus.armalib.lavaplayer.shadow.org.apache.http.client.methods.HttpGet;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.net.URI;
import java.net.URISyntaxException;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Optional;
import java.util.regex.Pattern;

public final class YoutubeCaptions {

    static final int MAX_BYTES = 4 * 1024 * 1024;

    private static final Pattern SOUND_TAGS = Pattern.compile("\\[[^\\]]*\\]|[♩♪♫♬]");

    public record Track(String baseUrl, String languageCode, String name, boolean autoGenerated) {}

    public interface Source {
        List<Track> captionsOf(String videoId);
    }

    private YoutubeCaptions() {}

    public static List<Track> tracksIn(JsonBrowser playerResponse) {
        List<Track> tracks = new ArrayList<>();
        try {
            JsonBrowser list = playerResponse.get("captions").get("playerCaptionsTracklistRenderer")
                    .get("captionTracks");
            for (JsonBrowser track : list.values()) {
                String url = track.get("baseUrl").text();
                String language = track.get("languageCode").text();
                if (url == null || language == null) continue;
                String name = track.get("name").get("simpleText").text();
                if (name == null) name = track.get("name").get("runs").index(0).get("text").text();
                tracks.add(new Track(url, language, name == null ? language : name,
                        "asr".equals(track.get("kind").text())));
            }
        } catch (RuntimeException e) {
            return List.of();
        }
        return List.copyOf(tracks);
    }

    public static Optional<Track> choose(List<Track> tracks, String playerLanguage) {
        if (!tracks.isEmpty() && com.nachtraben.soundstage.core.RigFaults.on("subtitle-first-track")) {
            return Optional.of(tracks.get(0));
        }
        List<Track> uploaded = tracks.stream().filter(track -> !track.autoGenerated()).toList();
        return LanguageMatch.best(playerLanguage, uploaded, Track::languageCode);
    }

    public static Optional<URI> vttUrl(Track track) {
        URI base;
        try {
            base = new URI(track.baseUrl());
        } catch (URISyntaxException e) {
            return Optional.empty();
        }
        if (!"https".equalsIgnoreCase(base.getScheme()) || !"www.youtube.com".equalsIgnoreCase(base.getHost())
                || base.getPort() != -1 || base.getUserInfo() != null || !"/api/timedtext".equals(base.getPath())) {
            return Optional.empty();
        }
        StringBuilder query = new StringBuilder();
        String raw = base.getRawQuery();
        if (raw != null) {
            for (String part : raw.split("&")) {
                if (part.isEmpty() || part.startsWith("fmt=")) continue;
                if (query.length() > 0) query.append('&');
                query.append(part);
            }
        }
        if (query.length() > 0) query.append('&');
        query.append("fmt=vtt");
        return Optional.of(URI.create("https://www.youtube.com/api/timedtext?" + query));
    }

    public static List<SubtitleCue> withoutSoundTags(List<SubtitleCue> cues) {
        List<SubtitleCue> kept = new ArrayList<>();
        for (SubtitleCue cue : cues) {
            SubtitleCue filtered = cue.mapText(YoutubeCaptions::withoutSoundTagLines);
            if (filtered != null) kept.add(filtered);
        }
        return kept;
    }

    private static String withoutSoundTagLines(String text) {
        StringBuilder out = new StringBuilder();
        for (String line : text.split("\n")) {
            if (SOUND_TAGS.matcher(line).replaceAll("").isBlank()) continue;
            if (out.length() > 0) out.append('\n');
            out.append(line);
        }
        return out.toString();
    }

    public static CueTrack fetch(YoutubeAudioSourceManager source, Track track) throws IOException {
        URI url = vttUrl(track).orElseThrow(() -> new IOException("its URL is not YouTube's timedtext endpoint"));
        try (HttpInterface http = source.getInterface();
             CloseableHttpResponse response = http.execute(new HttpGet(url))) {
            int status = response.getStatusLine().getStatusCode();
            if (status != 200) throw new IOException("YouTube answered " + status);
            if (response.getEntity() == null) throw new IOException("YouTube answered with nothing");
            String vtt;
            try (InputStream in = response.getEntity().getContent()) {
                vtt = new String(readBounded(in), StandardCharsets.UTF_8);
            }
            List<SubtitleCue> cues = CueParser.parseWebVtt(vtt);
            return new CueTrack(track.autoGenerated() ? withoutSoundTags(cues) : cues);
        }
    }

    private static byte[] readBounded(InputStream in) throws IOException {
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        byte[] buffer = new byte[8192];
        for (int n; (n = in.read(buffer)) >= 0; ) {
            if (out.size() + n > MAX_BYTES) throw new IOException("its captions are larger than " + MAX_BYTES + " bytes");
            out.write(buffer, 0, n);
        }
        return out.toByteArray();
    }

    private static String baseLanguage(String code) {
        int dash = code.indexOf('-');
        return (dash < 0 ? code : code.substring(0, dash)).toLowerCase(Locale.ROOT);
    }
}
